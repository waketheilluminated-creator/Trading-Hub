#!/usr/bin/env node
// Generates app/theme-light.css from app/globals.css.
//   node tools/gen-light-theme.mjs          write the file
//   node tools/gen-light-theme.mjs --check  exit 1 if the committed file is stale
// Every declaration in globals.css that carries a hard-coded colour gets a
// `html.theme-light …` override, so new dark styles cannot silently miss the light theme.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import { hasColor, mapDeclarationValue } from "../lib/theme-colors.js";

const ROOT = new URL("../", import.meta.url);
const SOURCE = fileURLToPath(new URL("app/globals.css", ROOT));
const TARGET = fileURLToPath(new URL("app/theme-light.css", ROOT));

// Surfaces that are intentionally light in both themes (embedded light charts).
const SKIP_SELECTOR = /cvd-oi-chart|cex-netflow-chart|cvd-oi-legend i|cex-netflow-legend i|cex-netflow-watermark/;

// Hand-tuned tokens: readable accents on white, TradingView-like light neutrals.
const LIGHT_TOKENS = `html.theme-light {
  color-scheme: light;
  --ink: #131722; --muted: #4a5466; --faint: #787f8c; --panel: #ffffff;
  --panel-2: #f0f3f7; --line: #d6dbe3; --bg: #f5f7fa; --accent: #0f8f55;
  --cyan: #0b84a0; --red: #d93a43; --amber: #b7791f;
}
`;

function prefixSelector(selector) {
  return selector.split(",").map((part) => {
    const s = part.trim();
    if (s === ":root" || s === "html") return "html.theme-light";
    if (s.startsWith("html")) return s.replace(/^html/, "html.theme-light");
    return `html.theme-light ${s}`;
  }).join(", ");
}

export function buildLightTheme(css) {
  const root = postcss.parse(css);
  const out = postcss.root();
  const emit = (rule, parent) => {
    if (SKIP_SELECTOR.test(rule.selector) || rule.selector.trim() === ":root") return;
    const decls = [];
    rule.each((node) => {
      if (node.type !== "decl" || node.prop.startsWith("--") || !hasColor(node.value)) return;
      decls.push(postcss.decl({ prop: node.prop, value: mapDeclarationValue(node.prop, node.value), important: node.important }));
    });
    if (!decls.length) return;
    const next = postcss.rule({ selector: prefixSelector(rule.selector) });
    decls.forEach((decl) => next.append(decl));
    parent.append(next);
  };
  root.each((node) => {
    if (node.type === "rule") emit(node, out);
    else if (node.type === "atrule" && node.name === "media") {
      const media = postcss.atRule({ name: "media", params: node.params });
      node.each((child) => { if (child.type === "rule") emit(child, media); });
      if (media.nodes?.length) out.append(media);
    }
  });
  out.each((node) => { node.raws.before = "\n"; });
  return `/* Generated by tools/gen-light-theme.mjs from globals.css — do not edit by hand. */\n${LIGHT_TOKENS}${out.toString().trim()}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = buildLightTheme(readFileSync(SOURCE, "utf8"));
  if (process.argv.includes("--check")) {
    const current = readFileSync(TARGET, "utf8");
    if (current !== next) { console.error("app/theme-light.css is stale: run node tools/gen-light-theme.mjs"); process.exit(1); }
  } else {
    writeFileSync(TARGET, next);
    console.log(`wrote ${TARGET}`);
  }
}
